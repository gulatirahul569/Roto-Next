export const departmentOptions = Object.values(departmentData)
  .filter((department) => department.key !== "ALL")
  .map((department) => ({
    key: department.key,
    slug: department.slug,
    title: department.title,
  }));

export function getDepartmentBySlug(slug = "") {
  return departmentData[String(slug).toLowerCase()] || null;
}

export function getDepartmentByKey(key = "") {
  return (
    Object.values(departmentData).find(
      (department) => department.key === String(key).toUpperCase(),
    ) || null
  );
}

export function getSubcategoryBySlug(departmentSlug = "", subcategorySlug = "") {
  const department = getDepartmentBySlug(departmentSlug);

  if (!department) {
    return null;
  }

  return (
    department.subcategories.find(
      (subcategory) =>
        subcategory.slug === String(subcategorySlug).toLowerCase(),
    ) || null
  );
}

export function getSubcategoryOptions(departmentKey = "") {
  const department = getDepartmentByKey(departmentKey);

  return department?.subcategories || [];
}
export function applyMediaOverrides(department, media = {}) {
  if (!department) {
    return null;
  }

  const departmentSlug = department.slug;

  const bannerKey = `banners/${departmentSlug}`;

  return {
    ...department,

    banner: media[bannerKey] || department.banner,

    subcategories: (department.subcategories || []).map(
      (subcategory) => {
        const subcategoryKey =
          `categories/${departmentSlug}/${subcategory.slug}`;

        return {
          ...subcategory,
          image: media[subcategoryKey] || subcategory.image,
        };
      },
    ),
  };
}